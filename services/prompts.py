def format_primary_email_prompt(
    operator_name: str,
    service_name: str,
    description: str,
    tech_params: dict,
    budget: str,
    deadlines: str,
    company: str,
    contact_person: str
) -> str:
    """
    Форматирование промпта для генерации первичного письма
    
    Args:
        operator_name: Название вашей компании
        service_name: Название услуги
        description: Описание услуги
        tech_params: Технические параметры (словарь)
        budget: Бюджет
        deadlines: Сроки
        company: Компания поставщика
        contact_person: Контактное лицо
        
    Returns:
        Отформатированный промпт
    """
    tech_params_str = '\n'.join([f"- {k}: {v}" for k, v in tech_params.items()])
    
    return PROMPT_GENERATE_PRIMARY_EMAIL.format(
        operator_name=operator_name,
        service_name=service_name,
        description=description,
        tech_params=tech_params_str if tech_params_str else "Не указаны",
        budget=budget if budget else "Не указан",
        deadlines=deadlines if deadlines else "Не указаны",
        company=company,
        contact_person=contact_person
    )


